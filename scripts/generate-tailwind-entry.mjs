import {readFileSync, writeFileSync, existsSync} from 'node:fs';

const path = new URL('../src/styles/tailwind.generated.css', import.meta.url);
const preview = process.env.TAILWIND_INCLUDE_GENERATED_PREVIEW_CLASSES === 'true';
const source = '/* Generated by npm run generate:styles. Do not edit. */\n'
  + '@import "./tailwind.css";\n'
  + (preview
    ? '@source inline("{hover:,focus:,active:,}{bg,text,from,to,via}-{red,orange,green,blue,purple,slate,neutral,zinc,yellow,teal}-{100,200,500,800,900}");\n'
      + '@source inline("bg-gradient-to-{r,l,t,b,tl,tr,bl,br}");\n'
    : '');

if (!existsSync(path) || readFileSync(path, 'utf8') !== source) {
  writeFileSync(path, source);
}
